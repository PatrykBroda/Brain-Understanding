import { readFileSync, readdirSync, writeFileSync, statSync, renameSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const VAULT_ROOT = path.resolve(here, "src/synochi");
const OUT = path.resolve(here, "src/lib/synochi.generated.ts");

const FULL = ["SPINE", "IDENTITY", "PROTOCOLS", "Interaction Psychology", "Guidance Dynamics"];
const DEEP = ["MODELS", "MECHANISMS"];

// Input budget. Every coach turn used to carry the whole vault (~120k tokens), which
// made each reply slow and expensive. The always-loaded layers now carry the HEAD of
// each note (definition, core law, rules: the part the coach leans on every turn)
// up to NOTE_CAP characters; the rest of a long note is "shelved" into the retrievable
// set and loads whole, on demand, the same way MODELS / MECHANISMS notes do. Nothing is
// deleted. SYNOCHI_VAULT_MODE=full restores the old always-loaded-in-full behaviour.
const FULL_MODE = process.env.SYNOCHI_VAULT_MODE === "full";
const NOTE_CAP = Number(process.env.SYNOCHI_NOTE_CAP ?? 1800);
const BLURB_CHARS = FULL_MODE ? 320 : Number(process.env.SYNOCHI_BLURB_CHARS ?? 150);

// Cut at a paragraph (else sentence, else word) boundary at or before `cap`.
function headOf(text, cap) {
  if (text.length <= cap) return text;
  const window = text.slice(0, cap);
  let cut = window.lastIndexOf("\n\n");
  if (cut < cap * 0.5) cut = Math.max(window.lastIndexOf(". "), window.lastIndexOf("\n"));
  if (cut < cap * 0.5) cut = window.lastIndexOf(" ");
  return window.slice(0, cut > 0 ? cut : cap).trimEnd();
}

/** folder -> title -> full text, for notes whose tail was cut from the always-loaded layer. */
const shelved = {};

function listMd(dir) {
  try {
    return readdirSync(dir).filter((f) => f.endsWith(".md")).map((f) => path.join(dir, f)).sort();
  } catch {
    return [];
  }
}

function clean(file) {
  return readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim();
}

function fullSection(folder) {
  const dir = path.join(VAULT_ROOT, folder);
  const parts = [`## ${folder}`, ""];
  for (const f of listMd(dir)) {
    const title = path.basename(f, ".md");
    const body = clean(f);
    parts.push(`### ${title}`);
    if (FULL_MODE || body.length <= NOTE_CAP) {
      parts.push(body);
    } else {
      parts.push(headOf(body, NOTE_CAP));
      parts.push(`[… shortened here — name [[${title}]] to load the rest]`);
      (shelved[folder] ??= {})[title] = body;
    }
    parts.push("");
  }
  return parts.join("\n");
}

function indexSection(folder) {
  const dir = path.join(VAULT_ROOT, folder);
  const parts = [
    `## ${folder} — concept index (titles + first lines)`,
    "",
    "These are nodes you can reason about by name. Use the framework principles to expand them; never contradict the SPINE. When you reference one, write it as [[Title]] — the retrieval layer will surface its full text into your context on the NEXT turn so you can quote it precisely.",
    "",
  ];
  for (const f of listMd(dir)) {
    const title = path.basename(f, ".md");
    const body = clean(f);
    const stripped = body
      .split("\n")
      .filter((l) => !l.trim().startsWith("[[") && !l.trim().startsWith("#") && l.trim().length > 0)
      .slice(0, 3)
      .join(" ")
      .slice(0, BLURB_CHARS);
    parts.push(`- **${title}** — ${stripped}`);
  }
  parts.push("");
  return parts.join("\n");
}

function deepMap(folder) {
  const dir = path.join(VAULT_ROOT, folder);
  const out = {};
  for (const f of listMd(dir)) {
    const title = path.basename(f, ".md");
    out[title] = clean(f);
  }
  return out;
}

if (!statSync(VAULT_ROOT, { throwIfNoEntry: false })?.isDirectory()) {
  throw new Error(`Vault not found at ${VAULT_ROOT}`);
}

const sections = [
  "# SYNOCHI — Personal Operating System (full reference)",
  "",
  "SPINE laws are non-negotiable. IDENTITY describes how the self forms and holds. PROTOCOLS are actionable interventions. MECHANISMS and MODELS are indexed below by title with short blurbs — when one becomes relevant to the conversation, the system surfaces its FULL TEXT into the dynamic context block under '# Deep vault context pulled in for this turn'. Always prefer the deep-block wording over your own paraphrase when available.",
  "",
];
for (const f of FULL) sections.push(fullSection(f));
for (const f of DEEP) sections.push(indexSection(f));

const vault = sections.join("\n");

const deep = {};
for (const f of DEEP) deep[f] = deepMap(f);
// Shelved tails of the always-loaded layers join the retrievable set under their own folder.
for (const f of Object.keys(shelved)) deep[f] = shelved[f];

const ts =
  `// AUTO-GENERATED by build-synochi.mjs. Do not edit by hand.\n` +
  `export const SYNOCHI_VAULT = ${JSON.stringify(vault)};\n` +
  `export const SYNOCHI_DEEP: Record<string, Record<string, string>> = ${JSON.stringify(deep)};\n`;

// Atomic write (tmp + rename): concurrent builds (dev workflow + smoke
// runners) regenerate this file with identical content; a plain write lets
// one build read a half-written file from another. rename() is atomic, so
// readers always see a complete old or new file.
const tmpOut = `${OUT}.tmp-${process.pid}`;
writeFileSync(tmpOut, ts);
renameSync(tmpOut, OUT);

const shelvedCount = Object.values(shelved).reduce((s2, m) => s2 + Object.keys(m).length, 0);
const deepCount = Object.values(deep).reduce((s, m) => s + Object.keys(m).length, 0);
const deepChars = Object.values(deep).reduce(
  (s, m) => s + Object.values(m).reduce((s2, b) => s2 + b.length, 0),
  0,
);
console.log(
  `Synochi vault bundled → ${OUT}\n  mode: ${FULL_MODE ? "full" : `compact (note cap ${NOTE_CAP}, blurb ${BLURB_CHARS}; ${shelvedCount} notes shelved to on-demand)`}\n  cached vault: ${vault.length} chars\n  deep nodes:   ${deepCount} (${deepChars} chars total, retrieved per turn)`,
);
